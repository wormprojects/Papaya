#!/usr/bin/env python3
"""
Turn the splash logo's two layers into include/logo.h (RGB565 pixels).

    tools/logo/mklogo.sh            (exports the layers from
                                     meta/papaya.aseprite, then runs this)
    python3 tools/logo/mklogo.py word.png note.png include/logo.h [overlay.png]

Both PNGs are the full Aseprite canvas, one layer each, with hard
(on/off) transparency. Each layer is cropped to its own pixels; the
offsets in the header are relative to the box both layers cover together,
which the splash centres on the screen. The note is drawn over the word.

An optional overlay PNG (a layer drawn over the word at partial opacity,
the opacity already in its alpha) is flattened onto the word first, only
where the word has pixels, so the word keeps hard transparency.

Pixels are stored column by column (like the top screen canvas), with
LOGO_KEY marking the transparent ones.

Needs Pillow.
"""

import sys

from PIL import Image

KEY = 0xF81F  # pure magenta: not used by the logo (checked below)


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def load(path):
    im = Image.open(path).convert("RGBA")
    alphas = {a for (_, _, _, a) in im.getdata()}
    if not alphas <= {0, 255}:
        sys.exit(f"{path}: partly transparent pixels {sorted(alphas)}; "
                 "the logo needs hard (on/off) transparency")
    box = im.getbbox()
    if box is None:
        sys.exit(f"{path}: empty layer")
    return im, box


def flatten(word, overlay_path):
    """The word with the overlay blended onto its own pixels."""
    over = Image.open(overlay_path).convert("RGBA")
    mixed = Image.alpha_composite(word, over)
    keep = word.getchannel("A")
    mixed.putalpha(keep)
    return mixed


def layer(name, im, box, ox, oy, out):
    x0, y0, x1, y1 = box
    w, h = x1 - x0, y1 - y0
    px = []
    for x in range(x0, x1):
        for y in range(y0, y1):
            r, g, b, a = im.getpixel((x, y))
            if a == 0:
                px.append(KEY)
            else:
                v = rgb565(r, g, b)
                if v == KEY:
                    sys.exit(f"{name}: a pixel converts to the "
                             f"transparent key 0x{KEY:04X}")
                px.append(v)
    out.append(f"static const uint16_t {name}Px[{w * h}] = {{")
    for i in range(0, len(px), 12):
        out.append("\t" + ", ".join(f"0x{v:04X}" for v in px[i:i + 12]) +
                   ",")
    out.append("};")
    out.append(f"static const struct logoLayer {name} = "
               f"{{ {x0 - ox}, {y0 - oy}, {w}, {h}, {name}Px }};")
    out.append("")


def main():
    if len(sys.argv) not in (4, 5):
        sys.exit(__doc__)
    word, wbox = load(sys.argv[1])
    if len(sys.argv) == 5:
        word = flatten(word, sys.argv[4])
    note, nbox = load(sys.argv[2])

    ox, oy = min(wbox[0], nbox[0]), min(wbox[1], nbox[1])
    w = max(wbox[2], nbox[2]) - ox
    h = max(wbox[3], nbox[3]) - oy

    out = [
        "/**",
        " * Papaya - 3DS Music Player",
        " * Splash logo, generated by tools/logo/mklogo.py from",
        " * meta/papaya.aseprite. Don't edit by hand: change the .aseprite",
        " * and run tools/logo/mklogo.sh.",
        " *",
        " * RGB565, column by column (x outer, y inner); LOGO_KEY pixels",
        " * are transparent. Included by topscreen.c only.",
        " */",
        "",
        "#ifndef ctrmus_logo_h",
        "#define ctrmus_logo_h",
        "",
        "#include <stdint.h>",
        "",
        f"#define LOGO_W\t\t{w}",
        f"#define LOGO_H\t\t{h}",
        f"#define LOGO_KEY\t0x{KEY:04X}",
        "",
        "struct logoLayer",
        "{",
        "\tint\t\t\t\tx, y;\t/* offset in the LOGO_W x LOGO_H box */",
        "\tint\t\t\t\tw, h;",
        "\tconst uint16_t*\tpx;",
        "};",
        "",
    ]
    layer("logoWord", word, wbox, ox, oy, out)
    layer("logoNote", note, nbox, ox, oy, out)
    out.append("#endif")

    with open(sys.argv[3], "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"{sys.argv[3]}: {w}x{h}, word {wbox}, note {nbox}")


if __name__ == "__main__":
    main()
